/* =========================================================
   GALLERY + LIGHTBOX
========================================================= */
function initGallery() {
  const tabs = document.querySelectorAll(".gtab");
  const items = document.querySelectorAll(".g-item");
  tabs.forEach(tab => {
    tab.addEventListener("click", () => {
      tabs.forEach(t => t.classList.remove("active"));
      tab.classList.add("active");
      const filter = tab.dataset.filter;
      items.forEach(item => {
        const match = filter === "all" || item.dataset.cat === filter;
        item.classList.toggle("hidden", !match);
      });
    });
  });

  const lightbox = document.getElementById("lightbox");
  const lbImg = document.getElementById("lbImg");
  const lbClose = document.getElementById("lbClose");
  const lbPrev = document.getElementById("lbPrev");
  const lbNext = document.getElementById("lbNext");
  let visibleItems = [];
  let currentIndex = 0;

  function openLightbox(item) {
    visibleItems = Array.from(items).filter(i => !i.classList.contains("hidden"));
    currentIndex = visibleItems.indexOf(item);
    lbImg.src = item.src;
    lbImg.alt = item.alt;
    lightbox.classList.add("open");
  }
  function showIndex(i) {
    currentIndex = (i + visibleItems.length) % visibleItems.length;
    lbImg.src = visibleItems[currentIndex].src;
    lbImg.alt = visibleItems[currentIndex].alt;
  }

  items.forEach(item => item.addEventListener("click", () => openLightbox(item)));
  lbClose.addEventListener("click", () => lightbox.classList.remove("open"));
  lightbox.addEventListener("click", (e) => { if (e.target === lightbox) lightbox.classList.remove("open"); });
  lbPrev.addEventListener("click", () => showIndex(currentIndex - 1));
  lbNext.addEventListener("click", () => showIndex(currentIndex + 1));
  document.addEventListener("keydown", (e) => {
    if (!lightbox.classList.contains("open")) return;
    if (e.key === "Escape") lightbox.classList.remove("open");
    if (e.key === "ArrowLeft") showIndex(currentIndex - 1);
    if (e.key === "ArrowRight") showIndex(currentIndex + 1);
  });
}

/* =========================================================
   FORM VALIDATION
========================================================= */
function validateForm(form) {
  let valid = true;
  const dict = translations[currentLang] || translations.en;

  const nameField = form.querySelector('[name="name"]');
  const phoneField = form.querySelector('[name="phone"]');
  const emailField = form.querySelector('[name="email"]');

  form.querySelectorAll(".field-error").forEach(el => el.textContent = "");

  if (nameField && nameField.value.trim().length < 2) {
    setError(form, "name", dict["form.err.name"]);
    valid = false;
  }
  if (phoneField) {
    const phonePattern = /^[0-9+\-\s()]{7,15}$/;
    if (!phonePattern.test(phoneField.value.trim())) {
      setError(form, "phone", dict["form.err.phone"]);
      valid = false;
    }
  }
  if (emailField) {
    const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailPattern.test(emailField.value.trim())) {
      setError(form, "email", dict["form.err.email"]);
      valid = false;
    }
  }
  return valid;
}

function setError(form, field, message) {
  const el = form.querySelector(`[data-error="${field}"]`);
  if (el) el.textContent = message;
}

function initFormValidation() {
  const heroForm = document.getElementById("heroForm");
  const contactForm = document.getElementById("contactForm");

  if (heroForm) {
    heroForm.addEventListener("submit", (e) => {
      e.preventDefault();
      if (validateForm(heroForm)) {
        document.getElementById("heroSuccess").hidden = false;
        heroForm.reset();
        setTimeout(() => { document.getElementById("heroSuccess").hidden = true; }, 5000);
      }
    });
  }

  if (contactForm) {
    contactForm.addEventListener("submit", (e) => {
      e.preventDefault();
      if (validateForm(contactForm)) {
        document.getElementById("contactSuccess").hidden = false;
        contactForm.reset();
        setTimeout(() => { document.getElementById("contactSuccess").hidden = true; }, 5000);
      }
    });
  }
}

